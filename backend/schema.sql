-- =====================================================================================
-- Masar - PostgreSQL schema (matches academics/models.py and the uploaded ERD). PG 14+.
-- In the Django project the migrations are the source of truth. Use this file for review,
-- a DBA, or a standalone database:   psql -f schema.sql && psql -f academics/db_rules.sql
-- =====================================================================================
BEGIN;

-- USERS = Django's auth_user (skip this block if Django migrations created it) -----------
CREATE TABLE IF NOT EXISTS auth_user (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password     varchar(128) NOT NULL,                       -- password_hash
    last_login   timestamptz,
    is_superuser boolean NOT NULL DEFAULT false,
    username     varchar(150) NOT NULL UNIQUE,
    first_name   varchar(150) NOT NULL DEFAULT '',
    last_name    varchar(150) NOT NULL DEFAULT '',
    email        varchar(254) NOT NULL DEFAULT '',
    is_staff     boolean NOT NULL DEFAULT false,
    is_active    boolean NOT NULL DEFAULT true,
    date_joined  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------- catalog ---------------
CREATE TABLE specializations (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code    varchar(10)  NOT NULL UNIQUE,                     -- CS, IT, IS, AI
    name_ar varchar(120) NOT NULL,
    name_en varchar(120) NOT NULL
);

CREATE TABLE semesters (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year         varchar(9)  NOT NULL,               -- '2025/2026'
    term                  varchar(6)  NOT NULL,
    start_date            date        NOT NULL,
    end_date              date        NOT NULL,
    registration_deadline timestamptz NOT NULL,
    is_current            boolean     NOT NULL DEFAULT false,
    CONSTRAINT uq_semester_year_term UNIQUE (academic_year, term),
    CONSTRAINT ck_semester_term_valid CHECK (term IN ('fall','spring','summer')),
    CONSTRAINT ck_semester_dates CHECK (end_date > start_date),
    CONSTRAINT ck_semester_year_format CHECK (academic_year ~ '^[0-9]{4}/[0-9]{4}$')
);
CREATE UNIQUE INDEX uq_semester_single_current ON semesters (is_current) WHERE is_current;

CREATE TABLE instructors (
    id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_en varchar(150) NOT NULL,
    name_ar varchar(150) NOT NULL DEFAULT '',
    email   varchar(254) UNIQUE                                -- optional, unique when present
);

CREATE TABLE degree_requirements (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope             varchar(12) NOT NULL,
    specialization_id bigint REFERENCES specializations(id) ON DELETE RESTRICT,
    requirement_type  varchar(12) NOT NULL,
    required_hours    smallint    NOT NULL,
    CONSTRAINT ck_degreq_scope_valid CHECK (scope IN ('general','faculty','department')),
    CONSTRAINT ck_degreq_requirement_type_valid CHECK (requirement_type IN ('compulsory','elective')),
    CONSTRAINT ck_degreq_hours_positive CHECK (required_hours > 0),
    CONSTRAINT ck_degreq_spec_iff_dept_scope CHECK (
        (scope = 'department' AND specialization_id IS NOT NULL)
     OR (scope <> 'department' AND specialization_id IS NULL))
);
CREATE UNIQUE INDEX uq_degreq_spec   ON degree_requirements (scope, specialization_id, requirement_type) WHERE specialization_id IS NOT NULL;
CREATE UNIQUE INDEX uq_degreq_global ON degree_requirements (scope, requirement_type)                    WHERE specialization_id IS NULL;

CREATE TABLE courses (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              varchar(10)  NOT NULL UNIQUE,
    title_en          varchar(200) NOT NULL,
    title_ar          varchar(200) NOT NULL DEFAULT '',
    description_en    text         NOT NULL DEFAULT '',
    description_ar    text         NOT NULL DEFAULT '',
    credit_hours      smallint     NOT NULL DEFAULT 3,         -- 2, 3 or 6
    lecture_hours     smallint     NOT NULL DEFAULT 2,
    lab_hours         smallint     NOT NULL DEFAULT 0,
    requirement_group varchar(12)  NOT NULL,
    requirement_type  varchar(12),                             -- NULL for department courses
    min_level         smallint     NOT NULL DEFAULT 1,
    typical_term      varchar(6)   NOT NULL DEFAULT 'both',
    is_active         boolean      NOT NULL DEFAULT true,
    CONSTRAINT ck_course_credits_positive CHECK (credit_hours > 0),
    CONSTRAINT ck_course_min_level_range CHECK (min_level BETWEEN 1 AND 4),
    CONSTRAINT ck_course_requirement_group_valid CHECK (requirement_group IN ('general','faculty','department')),
    CONSTRAINT ck_course_requirement_type_valid CHECK (requirement_type IS NULL OR requirement_type IN ('compulsory','elective')),
    CONSTRAINT ck_course_typical_term_valid CHECK (typical_term IN ('fall','spring','both')),
    CONSTRAINT ck_course_type_iff_not_dept CHECK (
        (requirement_group = 'department' AND requirement_type IS NULL)
     OR (requirement_group <> 'department' AND requirement_type IS NOT NULL))
);

CREATE TABLE department_courses (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialization_id bigint      NOT NULL REFERENCES specializations(id) ON DELETE RESTRICT,
    course_id         bigint      NOT NULL REFERENCES courses(id)         ON DELETE RESTRICT,
    requirement_type  varchar(12) NOT NULL,
    CONSTRAINT uq_deptcourse_spec_course UNIQUE (specialization_id, course_id),
    CONSTRAINT ck_deptcourse_requirement_type_valid CHECK (requirement_type IN ('compulsory','elective'))
);
CREATE INDEX ix_deptcourse_course ON department_courses (course_id);

CREATE TABLE course_prerequisites (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id              bigint   NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,   -- target course
    prerequisite_course_id bigint   NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,   -- required course
    "group"                smallint NOT NULL DEFAULT 1,       -- AND inside a group, OR across groups
    CONSTRAINT uq_prereq_course_prereq_group UNIQUE (course_id, prerequisite_course_id, "group"),
    CONSTRAINT ck_prereq_not_self CHECK (course_id <> prerequisite_course_id),
    CONSTRAINT ck_prereq_group_positive CHECK ("group" >= 1)
);
CREATE INDEX ix_prereq_prerequisite ON course_prerequisites (prerequisite_course_id);

CREATE TABLE grade_scales (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_letter   varchar(3)   NOT NULL UNIQUE,
    min_score      numeric(5,2) NOT NULL,
    max_score      numeric(5,2) NOT NULL,
    quality_points numeric(3,2) NOT NULL CHECK (quality_points BETWEEN 0 AND 4),
    is_passing     boolean      NOT NULL,
    CONSTRAINT ck_grade_score_range CHECK (min_score >= 0 AND max_score <= 100 AND max_score >= min_score)
);

CREATE TABLE level_thresholds (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_level   smallint    NOT NULL UNIQUE CHECK (academic_level BETWEEN 1 AND 4),
    min_earned_hours smallint    NOT NULL UNIQUE,              -- 0, 36, 72, 108
    ar_label         varchar(40) NOT NULL
);

CREATE TABLE credit_limit_rules (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    min_cgpa    numeric(3,2),                                  -- NULL = no lower bound
    max_cgpa    numeric(3,2),                                  -- NULL = no upper bound
    max_credits smallint NOT NULL CHECK (max_credits > 0),
    CONSTRAINT ck_creditlimit_band_valid CHECK (min_cgpa IS NULL OR max_cgpa IS NULL OR max_cgpa > min_cgpa)
);

CREATE TABLE system_settings (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         varchar(80)  NOT NULL UNIQUE,
    value       varchar(255) NOT NULL,
    description text         NOT NULL DEFAULT ''
);

-- ---------------------------------------------------------------- offerings -------------
CREATE TABLE course_offerings (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id     bigint      NOT NULL REFERENCES courses(id)   ON DELETE RESTRICT,
    semester_id   bigint      NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
    instructor_id bigint      REFERENCES instructors(id)        ON DELETE SET NULL,
    status        varchar(10) NOT NULL DEFAULT 'proposed',
    capacity      integer     CHECK (capacity IS NULL OR capacity >= 0),
    CONSTRAINT uq_offering_course_semester UNIQUE (course_id, semester_id),   -- no sections
    CONSTRAINT ck_offering_status_valid CHECK (status IN ('proposed','open','closed'))
);
CREATE INDEX ix_offering_sem_status ON course_offerings (semester_id, status);

CREATE TABLE offering_time_slots (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offering_id bigint     NOT NULL REFERENCES course_offerings(id) ON DELETE CASCADE,
    day_of_week varchar(3) NOT NULL,
    start_time  time       NOT NULL,
    end_time    time       NOT NULL,
    CONSTRAINT uq_slot_offering_day_start UNIQUE (offering_id, day_of_week, start_time),
    CONSTRAINT ck_slot_times CHECK (end_time > start_time),
    CONSTRAINT ck_slot_day_of_week_valid CHECK (day_of_week IN ('Sun','Mon','Tue','Wed','Thu','Sat'))
);

-- ---------------------------------------------------------------- students --------------
CREATE TABLE students (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               integer     NOT NULL UNIQUE REFERENCES auth_user(id) ON DELETE CASCADE,
    university_id         varchar(20) NOT NULL UNIQUE,
    full_name_ar          varchar(150) NOT NULL DEFAULT '',
    specialization_id     bigint      REFERENCES specializations(id) ON DELETE SET NULL,   -- NULL until chosen
    admission_semester_id bigint      NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
    academic_level        smallint    NOT NULL DEFAULT 1,      -- written only by close_semester
    status                varchar(10) NOT NULL DEFAULT 'active',
    created_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_student_level_range CHECK (academic_level BETWEEN 1 AND 4),
    CONSTRAINT ck_student_status_valid CHECK (status IN ('active','graduated','suspended'))
);
CREATE INDEX ix_student_specialization ON students (specialization_id);

CREATE TABLE enrollments (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        bigint       NOT NULL REFERENCES students(id)         ON DELETE RESTRICT,
    offering_id       bigint       NOT NULL REFERENCES course_offerings(id) ON DELETE RESTRICT,
    status            varchar(10)  NOT NULL DEFAULT 'registered',
    score             numeric(5,2),
    grade_letter      varchar(3),
    grade_points      numeric(3,2),
    graded_by_user_id integer      REFERENCES auth_user(id) ON DELETE SET NULL,
    graded_at         timestamptz,
    CONSTRAINT uq_enrollment_student_offering UNIQUE (student_id, offering_id),
    CONSTRAINT ck_enrollment_status_valid CHECK (status IN ('registered','completed','failed','withdrawn')),
    CONSTRAINT ck_enrollment_score_range  CHECK (score IS NULL OR score BETWEEN 0 AND 100),
    CONSTRAINT ck_enrollment_points_range CHECK (grade_points IS NULL OR grade_points BETWEEN 0 AND 4),
    CONSTRAINT ck_enrollment_grade_fields CHECK (
        (status IN ('registered','withdrawn') AND score IS NULL AND grade_letter IS NULL AND grade_points IS NULL)
     OR (status IN ('completed','failed') AND grade_letter IS NOT NULL AND grade_points IS NOT NULL))
);
CREATE INDEX ix_enroll_student_status ON enrollments (student_id, status);
CREATE INDEX ix_enroll_offering       ON enrollments (offering_id);

CREATE TABLE student_semester_records (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id               bigint       NOT NULL REFERENCES students(id)  ON DELETE RESTRICT,
    semester_id              bigint       NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
    level_at_time            smallint     NOT NULL,
    specialization_id_at_time bigint      REFERENCES specializations(id) ON DELETE SET NULL,
    credits_attempted        smallint     NOT NULL,
    credits_earned           smallint     NOT NULL,
    semester_gpa             numeric(3,2) NOT NULL,
    cumulative_gpa           numeric(3,2) NOT NULL,
    CONSTRAINT uq_semrecord_student_semester UNIQUE (student_id, semester_id),
    CONSTRAINT ck_semrecord_earned_le_attempted CHECK (credits_earned <= credits_attempted),
    CONSTRAINT ck_semrecord_gpa_range CHECK (semester_gpa BETWEEN 0 AND 4 AND cumulative_gpa BETWEEN 0 AND 4),
    CONSTRAINT ck_semrecord_level_range CHECK (level_at_time BETWEEN 1 AND 4)
);

CREATE TABLE student_department_changes (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id             bigint NOT NULL REFERENCES students(id)        ON DELETE RESTRICT,
    from_specialization_id bigint REFERENCES specializations(id)          ON DELETE RESTRICT,   -- NULL on first choice
    to_specialization_id   bigint NOT NULL REFERENCES specializations(id) ON DELETE RESTRICT,
    semester_id            bigint NOT NULL REFERENCES semesters(id)       ON DELETE RESTRICT,
    changed_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_deptchange_differs CHECK (from_specialization_id IS NULL OR from_specialization_id <> to_specialization_id)
);
CREATE INDEX ix_deptchange_student ON student_department_changes (student_id);

CREATE TABLE student_course_preferences (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id      bigint     NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    course_id       bigint     NOT NULL REFERENCES courses(id)  ON DELETE RESTRICT,
    preference_kind varchar(5) NOT NULL,
    CONSTRAINT uq_pref_student_course UNIQUE (student_id, course_id),
    CONSTRAINT ck_pref_preference_kind_valid CHECK (preference_kind IN ('want','avoid'))
);

-- ---------------------------------------------------------------- requests / AI ---------
CREATE TABLE summer_requests (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id               bigint      NOT NULL REFERENCES students(id)  ON DELETE RESTRICT,
    course_id                bigint      NOT NULL REFERENCES courses(id)   ON DELETE RESTRICT,
    semester_id              bigint      NOT NULL REFERENCES semesters(id) ON DELETE RESTRICT,
    fulfilled_by_offering_id bigint      REFERENCES course_offerings(id)   ON DELETE SET NULL,
    status                   varchar(10) NOT NULL DEFAULT 'pending',
    reason                   text        NOT NULL DEFAULT '',
    decided_by_user_id       integer     REFERENCES auth_user(id)          ON DELETE SET NULL,
    decided_at               timestamptz,
    created_at               timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_summer_student_course_sem UNIQUE (student_id, course_id, semester_id),
    CONSTRAINT ck_summer_status_valid CHECK (status IN ('pending','approved','rejected')),
    CONSTRAINT ck_summer_decided_at_iff_decided CHECK (
        (status = 'pending' AND decided_at IS NULL) OR (status <> 'pending' AND decided_at IS NOT NULL))
);
CREATE INDEX ix_summer_demand ON summer_requests (semester_id, course_id, status);

CREATE TABLE seventh_course_requests (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id         bigint      NOT NULL REFERENCES students(id)         ON DELETE RESTRICT,
    offering_id        bigint      NOT NULL REFERENCES course_offerings(id) ON DELETE RESTRICT,
    status             varchar(10) NOT NULL DEFAULT 'pending',
    reason             text        NOT NULL DEFAULT '',
    decided_by_user_id integer     REFERENCES auth_user(id) ON DELETE SET NULL,
    decided_at         timestamptz,
    created_at         timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_seventh_student_offering UNIQUE (student_id, offering_id),
    CONSTRAINT ck_seventh_status_valid CHECK (status IN ('pending','approved','rejected')),
    CONSTRAINT ck_seventh_decided_at_iff_decided CHECK (
        (status = 'pending' AND decided_at IS NULL) OR (status <> 'pending' AND decided_at IS NOT NULL))
);

CREATE TABLE specialization_recommendations (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id                  bigint       NOT NULL REFERENCES students(id)        ON DELETE CASCADE,
    recommended_specialization_id bigint     NOT NULL REFERENCES specializations(id) ON DELETE RESTRICT,
    confidence_score            numeric(4,3) NOT NULL CHECK (confidence_score BETWEEN 0 AND 1),
    top_3_rankings              jsonb        NOT NULL DEFAULT '[]',
    input_snapshot              jsonb        NOT NULL DEFAULT '{}',
    model_version               varchar(60)  NOT NULL CHECK (model_version <> ''),
    created_at                  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_reco_student_recent ON specialization_recommendations (student_id, created_at DESC);

CREATE TABLE notifications (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  bigint       NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    title_ar    varchar(200) NOT NULL DEFAULT '',
    title_en    varchar(200) NOT NULL,
    message_ar  text         NOT NULL DEFAULT '',
    message_en  text         NOT NULL DEFAULT '',
    type        varchar(20)  NOT NULL DEFAULT 'system',
    target_link varchar(200),                                  -- nullable UI route
    is_read     boolean      NOT NULL DEFAULT false,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_notification_type_valid CHECK (type IN
        ('request_approved','request_rejected','summer_fulfilled','system'))
);
CREATE INDEX ix_notif_student_unread ON notifications (student_id, is_read, created_at DESC);

COMMIT;